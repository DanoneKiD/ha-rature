export const LANGUES = { fr: 'Français', en: 'English', de: 'Deutsch' };

let langue = 'en';

/** `choix` : 'auto' (langue du téléphone) ou un code de LANGUES. */
export function definirLangue(choix) {
  const voulue = choix && choix !== 'auto' ? [choix] : navigator.languages ?? [navigator.language];
  langue = voulue.map((l) => String(l).slice(0, 2).toLowerCase()).find((l) => TEXTES[l]) ?? 'en';
  document.documentElement.lang = langue;
  return langue;
}

export const langueCourante = () => langue;

export function t(cle, vars = {}) {
  const s = TEXTES[langue][cle] ?? TEXTES.en[cle] ?? cle;
  return s.replace(/\{(\w+)\}/g, (_, k) => vars[k] ?? '');
}

/** Échappe un texte pour l'insérer dans un gabarit HTML. */
export const echapper = (s) => String(s ?? '').replace(/[&<>"]/g, (c) => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;' })[c]);

/** Texte d'une clé dans une langue donnée (reconnaître un libellé écrit dans une autre langue). */
t.dans = (l, cle) => TEXTES[l]?.[cle] ?? cle;
